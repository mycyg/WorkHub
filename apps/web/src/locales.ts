export type WebCopyKey = keyof typeof zh;

// 第一参数收 `boolean` 是过渡口子：这一层的渲染函数历史上大量以 `zh: boolean` 传语言，
// 把这些签名一起改成 `locale` 是另一件事，不该和「文案搬家」混在一批里。
export function webT(locale: WorkHubLocale | boolean, key: WebCopyKey): string {
  const isZh = typeof locale === "boolean" ? locale : normalizeWorkHubLocale(locale) === "zh-CN";
  return (isZh ? zh : en)[key];
}

// 带占位符的词典条目：`{name}` 按 vars 替换。整句留在词典里（两语同形），调用点只提供数值。
export function webTf(
  locale: WorkHubLocale | boolean,
  key: WebCopyKey,
  vars: Record<string, string | number>
): string {
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    webT(locale, key)
  );
}
