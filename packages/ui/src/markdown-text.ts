/**
 * 把一段 markdown 正文压成纯文本行（摘要、副标题、气泡里用）。
 *
 * R27（真机走查）：`预计 24-48 小时内完成` 在提议摘要里渲成了 `预计 24 48 小时内完成`。此前这层把
 * `-` 和 `#*_\`>` 一起塞进同一个字符类无差别替换成空格——列表符确实被抹掉了，但数字区间、连字词
 * （`e-mail`、`Meta-Planner`）里的连字符也一并被吃掉，读起来像少了一截。
 *
 * 现在分两步：`-` 只在**行首的列表符/分隔线**位置才算标记（`- 条目`、`* 条目`、`+ 条目`、`> 引用`、
 * `---`），行内一律原样保留；其余标记符仍旧无差别替换。最后把连续空白压成一个空格并去掉首尾空白。
 */
export function stripMarkdownMarkers(value: string | undefined): string {
  return (value ?? "")
    .replace(/^[ \t]*(?:[-*+>]|-{3,})(?=\s|$)/gmu, " ")
    .replace(/[#*_`>]/gu, " ")
    .replace(/\s+/gu, " ")
    .trim();
}
